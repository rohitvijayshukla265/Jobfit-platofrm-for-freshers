import express from 'express';
import multer from 'multer';
import { PrismaClient } from '@prisma/client';
import { authMiddleware } from './auth';

const router = express.Router();
const prisma = new PrismaClient();

const sendSuccess = (res: any, data: any = {}, message: string = '') => res.json({ success: true, data, message });
const sendError = (res: any, status: number, error: string, code: string = 'ERROR') => res.status(status).json({ success: false, error, code });

// Configure multer for audio upload
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: 10 * 1024 * 1024 }, // 10MB limit for audio
});

// ==========================================
// 5A. Communication Analyzer (Voice)
// ==========================================
router.post('/analyze', authMiddleware, upload.single('audio'), async (req: any, res: any) => {
  try {
    if (!req.file) return sendError(res, 400, 'No audio file uploaded', 'NO_FILE');

    const profile = await prisma.userProfile.findUnique({ where: { userId: req.userId } });
    if (!profile) return sendError(res, 404, 'Profile not found', 'NOT_FOUND');

    // Simulate S3 Upload
    const mockAudioUrl = `https://s3.amazonaws.com/careerpilot/voice/${req.userId}_${Date.now()}.webm`;
    const durationSecs = req.body.durationSecs ? parseInt(req.body.durationSecs) : 60;

    // Simulate AI Service Transcription & Analysis
    const fluencyScore = Math.floor(Math.random() * 20) + 70;
    const confidenceScore = Math.floor(Math.random() * 30) + 60;
    const speakingSpeed = Math.floor(Math.random() * 50) + 110;
    const fillerWords = Math.floor(Math.random() * 15);
    const clarityScore = Math.floor(Math.random() * 20) + 75;

    const transcript = "This is a simulated transcript generated by the AI voice service recognizing the audio.";
    const analysisJson = JSON.stringify({ fluencyScore, confidenceScore, speakingSpeed, fillerWords, clarityScore });

    // 1. Save Raw Recording
    const recording = await prisma.voiceRecording.create({
      data: {
        userId: req.userId,
        audioUrl: mockAudioUrl,
        transcript,
        durationSecs,
        analysis: analysisJson
      }
    });

    // 2. Generate Suggestions
    const suggestions = [];
    if (fillerWords > 5) suggestions.push(`You used ${fillerWords} filler words (um, ah, like). Try pausing silently instead.`);
    if (speakingSpeed > 150) suggestions.push('Your speaking speed is slightly fast. Try to pace yourself.');
    else if (speakingSpeed < 120) suggestions.push('Your speaking speed is a bit slow. Try to maintain a steady pace.');
    
    // 3. Save Report
    const report = await prisma.communicationReport.create({
      data: {
        profileId: profile.id,
        fluencyScore,
        confidenceScore,
        speakingSpeed,
        fillerWords,
        clarityScore,
        suggestions: JSON.stringify(suggestions),
      }
    });

    sendSuccess(res, { recording, report: { ...report, suggestions } }, 'Audio analyzed successfully');
  } catch (error: any) {
    sendError(res, 500, error.message, 'ANALYSIS_FAILED');
  }
});

router.get('/history', authMiddleware, async (req: any, res: any) => {
  try {
    const profile = await prisma.userProfile.findUnique({ where: { userId: req.userId } });
    if (!profile) return sendSuccess(res, []);

    const reports = await prisma.communicationReport.findMany({
      where: { profileId: profile.id },
      orderBy: { createdAt: 'desc' },
      take: 20
    });
    
    const parsedReports = reports.map(r => ({
      ...r,
      suggestions: r.suggestions ? JSON.parse(r.suggestions) : []
    }));
    sendSuccess(res, parsedReports);
  } catch (error: any) {
    sendError(res, 500, error.message, 'SERVER_ERROR');
  }
});

// ==========================================
// 5C. Vocabulary Builder
// ==========================================
router.get('/vocabulary', authMiddleware, async (req: any, res: any) => {
  try {
    // Fetch user's due words or get new ones
    const dueWords = await prisma.userVocabulary.findMany({
      where: { userId: req.userId, nextReview: { lte: new Date() } },
      include: { word: true },
      take: 10
    });

    if (dueWords.length < 10) {
      const existingWordIds = (await prisma.userVocabulary.findMany({ where: { userId: req.userId }, select: { wordId: true } })).map(uw => uw.wordId);
      const newWordsNeeded = 10 - dueWords.length;
      
      const newWords = await prisma.vocabularyWord.findMany({
        where: { id: { notIn: existingWordIds } },
        take: newWordsNeeded
      });

      // Add to user vocabulary
      if (newWords.length > 0) {
        await prisma.userVocabulary.createMany({
          data: newWords.map(w => ({ userId: req.userId, wordId: w.id }))
        });
        
        const addedWords = await prisma.userVocabulary.findMany({
          where: { userId: req.userId, wordId: { in: newWords.map(w => w.id) } },
          include: { word: true }
        });
        dueWords.push(...addedWords);
      }
    }

    sendSuccess(res, dueWords);
  } catch (err: any) {
    sendError(res, 500, err.message, 'SERVER_ERROR');
  }
});

router.post('/vocabulary/:id/review', authMiddleware, async (req: any, res: any) => {
  try {
    const { isCorrect } = req.body;
    const userVocab = await prisma.userVocabulary.findUnique({ where: { id: req.params.id } });
    if (!userVocab || userVocab.userId !== req.userId) return sendError(res, 404, 'Word not found', 'NOT_FOUND');

    let newStatus = userVocab.status;
    let newNextReview = new Date();
    
    // Simple mock spaced repetition
    if (isCorrect) {
      newStatus = userVocab.status === 'NEW' ? 'LEARNING' : 'MASTERED';
      newNextReview.setDate(newNextReview.getDate() + (newStatus === 'MASTERED' ? 7 : 1));
    } else {
      newStatus = 'LEARNING';
      newNextReview.setHours(newNextReview.getHours() + 1); // Review soon
    }

    const updated = await prisma.userVocabulary.update({
      where: { id: userVocab.id },
      data: { status: newStatus, nextReview: newNextReview, reviewCount: userVocab.reviewCount + 1 }
    });

    sendSuccess(res, updated, 'Review recorded');
  } catch (err: any) {
    sendError(res, 500, err.message, 'SERVER_ERROR');
  }
});

